#!/usr/bin/env bash
# 启动这台电脑上的 GHW 数字生命 (8765)。
# 默认只有一个生命。多体演示 (8766 bravo / 8767 alpha + zjev) 用 GHW_MULTI=1。
# 用法: scripts/start_ui_servers.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UI="$ROOT/zig-out/bin/ui_server"
UIDIR="$ROOT/ui"
GHW_DIR="${GHW_STATE_DIR:-$HOME/.local/share/ghw}"
PEERS="$GHW_DIR/peers.txt"
AUTO_TICK_MS="${GHW_AUTO_TICK_MS:-30000}"
MULTI="${GHW_MULTI:-0}"
# 无 LLM 实例默认与主实例同节奏。演示快心跳: GHW_AUTO_TICK_MS_FAST=2000
AUTO_TICK_MS_FAST="${GHW_AUTO_TICK_MS_FAST:-30000}"
# 模型可换，密钥只从环境变量读。例: GHW_LLM_MODEL=deepseek-v4-pro
LLM_PROVIDER="${GHW_LLM_PROVIDER:-deepseek}"
LLM_MODEL="${GHW_LLM_MODEL:-deepseek-flash}"
LLM_KEY_ENV="${GHW_LLM_KEY_ENV:-DEEPSEEK_API_KEY}"
LIFE_FILE="${GHW_LIFE:-$ROOT/config/life.mac.json}"
LIFE_ARGS=()
if [[ -f "$LIFE_FILE" ]]; then
  LIFE_ARGS=(--life "$LIFE_FILE")
fi
# System-0 决策核 (zjev sidecar): 只在多体演示里挂到 alpha
ZJEV_SERVE="$ROOT/../zjev/zig-out/bin/zjev-serve"
ZJEV_PORT="${GHW_ZJEV_PORT:-19377}"
ZJEV_ARGS=""
if [[ -x "$ZJEV_SERVE" ]]; then
  ZJEV_ARGS="--zjev-endpoint http://127.0.0.1:$ZJEV_PORT"
fi

if [[ ! -x "$UI" ]]; then
  echo "构建 ui_server..."
  (cd "$ROOT" && zig build install)
  UI="$ROOT/zig-out/bin/ui_server"
  if [[ ! -x "$UI" ]]; then
    UI="$(find "$ROOT/.zig-cache/o" -name ui_server -type f 2>/dev/null | head -1)"
  fi
fi

pkill -9 -f "$ROOT/zig-out/bin/ui_server" 2>/dev/null || true
pkill -9 -f "zjev-serve --port" 2>/dev/null || true
sleep 1

mkdir -p "$GHW_DIR"

# socket 清单 (Link 路径 = /tmp/ghw_{agent_id}.sock)
{
  echo "# GHW peer registry — regenerated by start_ui_servers.sh"
  echo "/tmp/ghw_ghw-ui.sock"
  if [[ "$MULTI" == "1" ]]; then
    echo "/tmp/ghw_bravo.sock"
    echo "/tmp/ghw_alpha.sock"
  fi
} > "$PEERS"

nohup "$UI" --port 8765 --id ghw-ui \
  --state "$GHW_DIR/ui_state.json" --ui-dir "$UIDIR" \
  --auto-tick-ms "$AUTO_TICK_MS" \
  --peers-file "$PEERS" \
  --llm "$LLM_PROVIDER" --llm-model "$LLM_MODEL" --llm-key-env "$LLM_KEY_ENV" \
  "${LIFE_ARGS[@]}" \
  >>/tmp/ui_server_8765.log 2>&1 &

PORTS=(8765)
if [[ "$MULTI" == "1" ]]; then
  PORTS+=(8766 8767)
  nohup "$UI" --port 8766 --id bravo \
    --state /tmp/state_bravo.json --ui-dir "$UIDIR" \
    --auto-tick-ms "$AUTO_TICK_MS_FAST" \
    --peers-file "$PEERS" --llm none \
    >>/tmp/ui_server_8766.log 2>&1 &
  nohup "$UI" --port 8767 --id alpha \
    --state /tmp/state_alpha.json --ui-dir "$UIDIR" \
    --auto-tick-ms "$AUTO_TICK_MS_FAST" \
    --peers-file "$PEERS" --llm none $ZJEV_ARGS \
    >>/tmp/ui_server_8767.log 2>&1 &
  if [[ -x "$ZJEV_SERVE" ]]; then
    (cd "$ROOT/../zjev" && nohup ./zig-out/bin/zjev-serve --port "$ZJEV_PORT" \
      --mock-mode peaked --profiles-dir model/calibration \
      >>/tmp/zjev_serve.log 2>&1 &)
    echo "System-0 决策核: zjev-serve :$ZJEV_PORT → alpha"
  fi
fi

sleep 4
for p in "${PORTS[@]}"; do
  code=$(curl -s -m 3 -o /dev/null -w '%{http_code}' "http://127.0.0.1:$p/" 2>/dev/null || echo 000)
  tick=$(curl -s -m 5 "http://127.0.0.1:$p/api/state" 2>/dev/null | python3 -c 'import sys,json; print(json.load(sys.stdin).get("tick","?"))' 2>/dev/null || echo "?")
  echo "  :$p  HTTP=$code  tick=$tick"
done
echo "打开 http://127.0.0.1:8765/  (日志: /tmp/ui_server_8765.log)"
if [[ "$MULTI" == "1" ]]; then
  echo "多体演示: 8765=${AUTO_TICK_MS}ms bravo/alpha=${AUTO_TICK_MS_FAST}ms"
else
  echo "一个生命: 8765 每 ${AUTO_TICK_MS}ms 一拍。多体演示: GHW_MULTI=1 $0"
fi
echo "守护: nohup scripts/watch_ui_servers.sh >>/tmp/ui_watchdog.log 2>&1 &"
