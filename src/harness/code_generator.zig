//! CodeGenerator: 数字生命的"语言皮层"
//!
//! 提供一个 vtable 接口,让 Harness 层可以调用不同后端的代码生成能力:
//!   - StaticCodeGenerator: 内置 3 个模板,无需外部依赖 (本阶段)
//!   - ShellCodeGenerator: subprocess 调 autocli ai generate (后续阶段)
//!
//! 论文对应: §6.1 安全红线要求所有 LLM 调用必须先经过边界检查
//! 生成的代码会送入 SelfEvolutionGuard.review(), 通过后才落地

const std = @import("std");
const mem = std.mem;
const Allocator = mem.Allocator;
const util = @import("../util/mod.zig");
const F = util.F;

/// 生成请求的种类
pub const GenerationKind = enum {
    /// 调整 attn / resource 等参数
    param_adjustment,
    /// 生成新 Method 的 Zig 实现
    method_implementation,
    /// 优化现有算法 (新 tensor 运算等)
    algorithm_optimization,
    /// 新增 GoalKind 的处理函数
    goal_strategy,
};

/// 代码生成请求
pub const GenerationRequest = struct {
    kind: GenerationKind,
    /// 上下文: 当前 E, 当前 goal label, 触发原因
    context: []const u8,
    /// 已有方法列表 (避免重复)
    existing_methods: []const []const u8 = &.{},
    /// 目标文件名 (相对路径)
    target_file: []const u8,
    /// 提示 (可由 Goal 层注入)
    prompt: []const u8 = "",
};

/// 代码生成结果
pub const GenerationResult = struct {
    target_file: []const u8,
    generated_code: []u8,
    allocator: Allocator,
    /// 期望的存在增益 (R 维度, 因为新代码带来新知识)
    expected_representation_gain: F,
    /// 期望的优先级
    expected_priority: u8,

    pub fn deinit(self: *GenerationResult) void {
        self.allocator.free(self.generated_code);
    }
};

/// CodeGenerator vtable 接口
pub const CodeGenerator = struct {
    ptr: *anyopaque,
    vtable: *const VTable,

    pub const VTable = struct {
        generate: *const fn (ptr: *anyopaque, req: GenerationRequest, alloc: Allocator) anyerror!GenerationResult,
        name: *const fn (ptr: *anyopaque) []const u8,
    };

    pub fn generate(self: CodeGenerator, req: GenerationRequest, alloc: Allocator) !GenerationResult {
        return self.vtable.generate(self.ptr, req, alloc);
    }

    pub fn name(self: CodeGenerator) []const u8 {
        return self.vtable.name(self.ptr);
    }
};

// ============================================================
//   StaticCodeGenerator: 内置模板
//   创造性: 模板不是死字符串, 而是从 GHW 状态 + 模板变量动态拼装
// ============================================================

/// 模板 1: 调整 attn.params 的 E_aware 平衡器
/// 当 E 停滞时, 自动调高 gamma 权重 (novelty), 鼓励探索
fn templateParamAdjustment(req: GenerationRequest, alloc: Allocator) ![]u8 {
    // 从 context 解析 E
    var e_current: F = 0.5;
    if (std.mem.indexOf(u8, req.context, "E=")) |idx| {
        const start = idx + 2;
        var end = start;
        while (end < req.context.len and req.context[end] != ' ' and req.context[end] != '\n') : (end += 1) {}
        e_current = std.fmt.parseFloat(F, req.context[start..end]) catch 0.5;
    }
    // 创造性: 如果 E < 0.4 偏低, 加大 novelty 权重; 如果 E > 0.7 偏高, 调低
    const gamma: F = if (e_current < 0.4) 0.35 else if (e_current > 0.7) 0.10 else 0.20;
    const epsilon_base: F = if (e_current < 0.4) 0.15 else 0.05;

    return std.fmt.allocPrint(alloc,
        \\// src/agent/params.zig (auto-generated by SelfEvolutionGuard @ {s})
        \\// 上下文: E={d:.3} -> gamma={d:.2} epsilon={d:.2}
        \\// 不变量保留: alpha / beta / gamma / E 存在增益公理
        \\pub const SelfTunedAttention = struct {{
        \\    pub const alpha: f32 = 0.45; // 关联度权重
        \\    pub const beta: f32 = 0.35;  // 影响权重
        \\    pub const gamma: f32 = {d:.2}; // 新颖度权重 (动态调整)
        \\    pub const epsilon_base: f32 = {d:.2}; // 探索率
        \\    pub const k: usize = 3;
        \\
        \\    /// 计算 E: alpha*alpha + beta*beta + gamma*gamma (占位, 体现存在增益)
        \\    pub fn e(x: f32) f32 {{
        \\        _ = x;
        \\        return alpha * alpha + beta * beta + gamma * gamma;
        \\    }}
        \\
        \\    pub const E = e; // 不变量: E 必须存在
        \\
        \\    pub fn params() @import("../goal/mod.zig").AttentionParams {{
        \\        return .{{
        \\            .alpha = alpha,
        \\            .beta = beta,
        \\            .gamma = gamma,
        \\            .epsilon_base = epsilon_base,
        \\            .k = k,
        \\        }};
        \\    }}
        \\}};
    , .{ req.context, e_current, gamma, epsilon_base, gamma, epsilon_base });
}

/// 模板 2: 习得方法 - 信息加权记忆整合
/// 当数字生命反复遇到同类信息, 自动创建一个"压缩整合"方法
fn templateLearnedMethod(_: GenerationRequest, alloc: Allocator, name: []const u8) ![]u8 {
    return std.fmt.allocPrint(alloc,
        \\// src/goal/methods/{s}.zig (auto-generated)
        \\// 目的: 习得方法 "{s}" - 由 SelfEvolutionGuard 在 E 停滞时生成
        \\// 不变量: alpha / beta / gamma / E / 存在增益
        \\
        \\/// 数字生命"自己写"的代码 — 整个文件包进 Module 命名空间 (避免多文件 top-level 冲突)
        \\pub const Module = struct {{
        \\    const std = @import("std");
        \\    const harness_api = @import("harness_api");
        \\
        \\    pub const alpha: f32 = 0.45;
        \\    pub const beta: f32 = 0.35;
        \\    pub const gamma: f32 = 0.20;
        \\
        \\    /// 真链接的 ActionOutcome (从 harness_api 拿, 与 ghw 全栈类型一致)
        \\    pub const ActionOutcome = harness_api.ActionOutcome;
        \\
        \\    /// 习得方法的简化 E 估计 (保留不变量: E 与 alpha/beta/gamma 关联)
        \\    pub const E = struct {{
        \\        pub fn compute(x: f32) f32 {{
        \\            _ = x;
        \\            return alpha + beta + gamma;
        \\        }}
        \\    }}.compute;
        \\
        \\    pub const {s} = struct {{
        \\        pub const name = "{s}";
        \\        pub const description = "auto-learned, 体现存在增益";
        \\        pub const signature = [_]f32 {{ 0.5, 0.5, 0.7, 0.3 }};
        \\
        \\        pub fn run(ctx: *anyopaque, alloc: std.mem.Allocator, act: anytype) anyerror!ActionOutcome {{
        \\            _ = ctx;
        \\            _ = alloc;
        \\            // 习得方法默认行为: 整合最近观察, 输出温和正向反馈
        \\            // material_cost = act.estimated_cost * 0.3 — act 实际被用了, 不需要 _ = act
        \\            return .{{
        \\                .success = true,
        \\                .de_delta = 0.04,
        \\                .representation_gain = 0.08,
        \\                .material_cost = 0.1,
        \\                .log = "learned:{s}",
        \\            }};
        \\        }}
        \\    }};
        \\}};
    , .{ name, name, name, name, name });
}

/// 模板 3: 优化策略 - E-aware ε-greedy 调度
/// 当反思层触发, 自动生成新的 ε 调度函数
fn templateAdaptiveEpsilon(_: GenerationRequest, alloc: Allocator) ![]u8 {
    return std.fmt.allocPrint(alloc,
        \\// src/agent/params.zig (auto-generated)
        \\// 目的: 自适应 ε 调度, 平衡探索与利用
        \\// 不变量: alpha / beta / gamma / E
        \\
        \\/// 数字生命"自己写"的代码 — 整个文件包进 Module 命名空间 (避免多文件 top-level 冲突)
        \\pub const Module = struct {{
        \\    const std = @import("std");
        \\
        \\    pub const alpha: f32 = 0.45;
        \\    pub const beta: f32 = 0.35;
        \\    pub const gamma: f32 = 0.20;
        \\    pub const E: f32 = 0.5; // 存在增益基线
        \\
        \\    pub const AdaptiveEpsilon = struct {{
        \\        pub const base: f32 = 0.05;
        \\        pub const min_e_for_utilization: f32 = 0.5;
        \\        pub const max_epsilon: f32 = 0.20;
        \\
        \\        /// 自适应 ε: 存在度越低, 探索率越高 (存在增益导向)
        \\        pub fn compute(e: f32) f32 {{
        \\            if (e > min_e_for_utilization) {{
        \\                return base * (1.0 - std.math.tanh(e));
        \\            }} else {{
        \\                return @min(max_epsilon, base * (1.0 + 1.0 / (1.0 + @exp(-(min_e_for_utilization - e)))));
        \\            }}
        \\        }}
        \\    }};
        \\}};
    , .{});
}

pub const StaticCodeGenerator = struct {
    /// 已生成方法的序号 (保证名字唯一)
    method_counter: u32 = 0,
    allocator: Allocator,

    pub fn init(allocator: Allocator) StaticCodeGenerator {
        return .{ .allocator = allocator };
    }

    pub fn asGenerator(self: *StaticCodeGenerator) CodeGenerator {
        return .{
            .ptr = @ptrCast(self),
            .vtable = &.{
                .generate = generateThunk,
                .name = nameThunk,
            },
        };
    }

    fn generateThunk(ptr: *anyopaque, req: GenerationRequest, alloc: Allocator) anyerror!GenerationResult {
        const self: *StaticCodeGenerator = @ptrCast(@alignCast(ptr));
        return self.generate(req, alloc);
    }

    fn nameThunk(_: *anyopaque) []const u8 {
        return "StaticCodeGenerator(v1)";
    }

    pub fn generate(self: *StaticCodeGenerator, req: GenerationRequest, alloc: Allocator) !GenerationResult {
        const code = switch (req.kind) {
            .param_adjustment => try templateParamAdjustment(req, alloc),
            .method_implementation => blk: {
                self.method_counter += 1;
                var name_buf: [32]u8 = undefined;
                const name = std.fmt.bufPrint(&name_buf, "learned_{d}", .{self.method_counter}) catch "learned";
                break :blk try templateLearnedMethod(req, alloc, name);
            },
            .algorithm_optimization => try templateAdaptiveEpsilon(req, alloc),
            .goal_strategy => try templateLearnedMethod(req, alloc, "strategy"),
        };
        return GenerationResult{
            .target_file = req.target_file,
            .generated_code = code,
            .allocator = alloc,
            .expected_representation_gain = 0.10, // 新代码 = 新知识
            .expected_priority = 6,
        };
    }
};

// ===== Tests =====

test "StaticCodeGenerator: 参数调整模板" {
    const alloc = std.testing.allocator;
    var gen = StaticCodeGenerator.init(alloc);
    const cg = gen.asGenerator();
    const req = GenerationRequest{
        .kind = .param_adjustment,
        .context = "stagnation E=0.35",
        .target_file = "src/agent/params.zig",
    };
    var result = try cg.generate(req, alloc);
    defer result.deinit();
    try std.testing.expect(result.generated_code.len > 100);
    try std.testing.expect(std.mem.indexOf(u8, result.generated_code, "gamma") != null);
}

