test "StaticCodeGenerator: 序号自增" {
    const alloc = std.testing.allocator;
    var gen = StaticCodeGenerator.init(alloc);
    try std.testing.expectEqual(@as(u32, 0), gen.method_counter);
    {
        var r1 = try gen.generate(.{ .kind = .method_implementation, .context = "", .target_file = "x.zig" }, alloc);
        defer r1.deinit();
        try std.testing.expectEqual(@as(u32, 1), gen.method_counter);
    }
    {
        var r2 = try gen.generate(.{ .kind = .method_implementation, .context = "", .target_file = "x.zig" }, alloc);
        defer r2.deinit();
        try std.testing.expectEqual(@as(u32, 2), gen.method_counter);
    }
}
